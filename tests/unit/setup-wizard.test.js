'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

let mockPromptAnswer = '';
let mockPromptAnswersBySubstring = {};

jest.mock('node:readline', () => ({
	createInterface: jest.fn(() => ({
		question: jest.fn((q, cb) => {
			for (const [pattern, answer] of Object.entries(mockPromptAnswersBySubstring)) {
				if (q.includes(pattern)) {
					return cb(answer);
				}
			}
			cb(mockPromptAnswer);
		}),
		close: jest.fn(),
	})),
}));

const wizard = require('../../scripts/setup-wizard');

beforeEach(() => {
	mockPromptAnswer = '';
	mockPromptAnswersBySubstring = {};
});

describe('parseArgs', () => {
	it('defaults to interactive without flags', () => {
		const opts = wizard.parseArgs(['node', 'script.js']);
		expect(opts.nonInteractive).toBe(false);
		expect(opts.minimal).toBe(false);
		expect(opts.dryRun).toBe(false);
		expect(opts.help).toBe(false);
	});

	it('parses --non-interactive and --minimal together', () => {
		const opts = wizard.parseArgs(['node', 'script.js', '--non-interactive', '--minimal']);
		expect(opts.nonInteractive).toBe(true);
		expect(opts.minimal).toBe(true);
	});

	it('parses --help and --dry-run', () => {
		const opts = wizard.parseArgs(['node', 'script.js', '--help', '--dry-run']);
		expect(opts.help).toBe(true);
		expect(opts.dryRun).toBe(true);
	});
});

describe('parseExistingEnv', () => {
	it('parses simple key=value pairs', () => {
		const parsed = wizard.parseExistingEnv('FOO=bar\nBAZ=qux\n');
		expect(parsed).toEqual({ FOO: 'bar', BAZ: 'qux' });
	});

	it('strips comments and blank lines', () => {
		const parsed = wizard.parseExistingEnv('# comment\n\nFOO=bar\n# trailing\n');
		expect(parsed).toEqual({ FOO: 'bar' });
	});

	it('unwraps quoted values', () => {
		const parsed = wizard.parseExistingEnv('FOO="hello world"\nBAR=\'single\'\n');
		expect(parsed).toEqual({ FOO: 'hello world', BAR: 'single' });
	});

	it('returns empty object for empty content', () => {
		const parsed = wizard.parseExistingEnv('');
		expect(parsed).toEqual({});
	});
});

describe('serializeEnv', () => {
	it('renders sorted key=value pairs', () => {
		const out = wizard.serializeEnv([['Z', '1'], ['A', '2']]);
		expect(out).toMatch(/^# Generated by/);
		expect(out).toMatch(/A=2/);
		expect(out).toMatch(/Z=1/);
	});

	it('quotes values with whitespace', () => {
		const out = wizard.serializeEnv([['KEY', 'has space']]);
		expect(out).toMatch(/KEY="has space"/);
	});

	it('escapes quotes and backslashes in quoted values', () => {
		const out = wizard.serializeEnv([['KEY', 'quote"and\\slash']]);
		expect(out).toMatch(/KEY="quote\\"and\\\\slash"/);
	});
});

describe('generateApiKey and generateCallbackSecret', () => {
	it('produces a 32-byte base64url-encoded key', () => {
		const key = wizard.generateApiKey();
		expect(typeof key).toBe('string');
		expect(key.length).toBeGreaterThanOrEqual(42);
		expect(key.length).toBeLessThanOrEqual(44);
		expect(key).toMatch(/^[A-Za-z0-9_-]+$/);
	});

	it('produces a unique value per call', () => {
		expect(wizard.generateApiKey()).not.toEqual(wizard.generateApiKey());
	});

	it('generateCallbackSecret returns base64url with no padding', () => {
		const secret = wizard.generateCallbackSecret();
		expect(secret).not.toMatch(/=/);
		expect(secret).toMatch(/^[A-Za-z0-9_-]+$/);
	});
});

describe('diffEnvKeys', () => {
	it('identifies added and changed keys', () => {
		const existing = { A: '1', B: '2' };
		const next = new Map([['A', '1'], ['B', '3'], ['C', '4']]);
		const diff = wizard.diffEnvKeys(existing, next);
		expect(diff.added).toEqual(['C']);
		expect(diff.changed).toEqual(['B']);
	});

	it('accepts plain object next', () => {
		const existing = { A: '1' };
		const next = { A: '1', B: '2' };
		const diff = wizard.diffEnvKeys(existing, next);
		expect(diff.added).toEqual(['B']);
		expect(diff.changed).toEqual([]);
	});

	it('returns empty arrays when entries are identical', () => {
		const existing = { A: '1' };
		const next = new Map([['A', '1']]);
		const diff = wizard.diffEnvKeys(existing, next);
		expect(diff.added).toEqual([]);
		expect(diff.changed).toEqual([]);
	});
});

describe('resolveMinimalAnswers', () => {
	it('generates fresh keys and disables telegram bot', () => {
		const a = wizard.resolveMinimalAnswers();
		expect(a.WEBHOOK_API_KEY).toMatch(/^[A-Za-z0-9_-]+$/);
		expect(a.JOB_CALLBACK_SIGNING_SECRET).toMatch(/^[A-Za-z0-9_-]+$/);
		expect(a.ENABLE_TELEGRAM_BOT).toBe('false');
	});

	it('produces distinct keys across calls', () => {
		const a = wizard.resolveMinimalAnswers();
		const b = wizard.resolveMinimalAnswers();
		expect(a.WEBHOOK_API_KEY).not.toEqual(b.WEBHOOK_API_KEY);
		expect(a.JOB_CALLBACK_SIGNING_SECRET).not.toEqual(b.JOB_CALLBACK_SIGNING_SECRET);
	});
});

describe('REQUIRED_KEYS', () => {
	it('lists WEBHOOK_API_KEY', () => {
		expect(wizard.REQUIRED_KEYS).toContain('WEBHOOK_API_KEY');
	});
});

describe('backupEnv', () => {
	it('returns null when source does not exist', () => {
		expect(wizard.backupEnv('/tmp/cabros-wizard-nonexistent-' + Date.now())).toBeNull();
	});

	it('creates a backup file when source exists', () => {
		const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cabros-wizard-backup-'));
		const envPath = path.join(tmpDir, '.env');
		fs.writeFileSync(envPath, 'FOO=bar\n');
		try {
			const backupPath = wizard.backupEnv(envPath);
			expect(backupPath).toBeTruthy();
			expect(fs.existsSync(backupPath)).toBe(true);
			expect(fs.readFileSync(backupPath, 'utf8')).toBe('FOO=bar\n');
			expect(fs.statSync(backupPath).mode & 0o777).toBe(0o600);
		} finally {
			fs.rmSync(tmpDir, { recursive: true, force: true });
		}
	});
});

describe('runWizard', () => {
	let tmpDir;
	let envPath;
	const silentStdout = { write: jest.fn() };

	beforeEach(() => {
		tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cabros-wizard-run-'));
		envPath = path.join(tmpDir, '.env');
		silentStdout.write.mockClear();
	});

	afterEach(() => {
		if (tmpDir && fs.existsSync(tmpDir)) {
			fs.rmSync(tmpDir, { recursive: true, force: true });
		}
	});

	it('creates a minimal .env with 0o600 permissions in non-interactive mode', async () => {
		const code = await wizard.runWizard({
			envPath,
			nonInteractive: true,
			minimal: true,
			stdout: silentStdout,
		});
		expect(code).toBe(0);
		expect(fs.existsSync(envPath)).toBe(true);
		expect(fs.statSync(envPath).mode & 0o777).toBe(0o600);

		const parsed = wizard.parseExistingEnv(fs.readFileSync(envPath, 'utf8'));
		expect(parsed.WEBHOOK_API_KEY).toMatch(/^[A-Za-z0-9_-]+$/);
		expect(parsed.JOB_CALLBACK_SIGNING_SECRET).toMatch(/^[A-Za-z0-9_-]+$/);
		expect(parsed.ENABLE_TELEGRAM_BOT).toBe('false');
	});

	it('preserves existing variables and creates a backup when updating an existing .env', async () => {
		fs.writeFileSync(envPath, 'PORT=4000\nCUSTOM_VAR=hello\n', { mode: 0o600 });

		const code = await wizard.runWizard({
			envPath,
			nonInteractive: true,
			minimal: true,
			stdout: silentStdout,
		});
		expect(code).toBe(0);

		const parsed = wizard.parseExistingEnv(fs.readFileSync(envPath, 'utf8'));
		expect(parsed.PORT).toBe('4000');
		expect(parsed.CUSTOM_VAR).toBe('hello');
		expect(parsed.WEBHOOK_API_KEY).toBeTruthy();

		const backupPath = `${envPath}.wizard.bak`;
		expect(fs.existsSync(backupPath)).toBe(true);
		expect(fs.statSync(backupPath).mode & 0o777).toBe(0o600);
		const backupParsed = wizard.parseExistingEnv(fs.readFileSync(backupPath, 'utf8'));
		expect(backupParsed.PORT).toBe('4000');
		expect(backupParsed.CUSTOM_VAR).toBe('hello');
	});

	it('does not write .env when dryRun is true', async () => {
		const code = await wizard.runWizard({
			envPath,
			dryRun: true,
			nonInteractive: true,
			minimal: true,
			stdout: silentStdout,
		});
		expect(code).toBe(0);
		expect(fs.existsSync(envPath)).toBe(false);
	});

	it('configures telegram bot as enabled when BOT_TOKEN is entered interactively', async () => {
		mockPromptAnswersBySubstring = {
			BOT_TOKEN: '123456:TEST_TOKEN',
		};

		const code = await wizard.runWizard({ envPath, stdout: silentStdout });
		expect(code).toBe(0);
		expect(fs.existsSync(envPath)).toBe(true);

		const parsed = wizard.parseExistingEnv(fs.readFileSync(envPath, 'utf8'));
		expect(parsed.BOT_TOKEN).toBe('123456:TEST_TOKEN');
		expect(parsed.ENABLE_TELEGRAM_BOT).toBe('true');
		expect(parsed.WEBHOOK_API_KEY).toBeTruthy();
	});

	it('disables telegram bot when BOT_TOKEN is skipped interactively', async () => {
		mockPromptAnswer = '';

		const code = await wizard.runWizard({ envPath, stdout: silentStdout });
		expect(code).toBe(0);
		expect(fs.existsSync(envPath)).toBe(true);

		const parsed = wizard.parseExistingEnv(fs.readFileSync(envPath, 'utf8'));
		expect(parsed.BOT_TOKEN).toBeUndefined();
		expect(parsed.ENABLE_TELEGRAM_BOT).toBe('false');
	});
});
